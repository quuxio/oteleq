"""Create and validate small owned suites which plan against current source."""
import json
import os
from pathlib import Path
import sys
import tomllib

import project_runner
import policy as project_policy

KIND = "oteleq-current-source-tests"
PROJECT = "project.json"
POLICY = "project-policy.toml"
RUNNER = "test_equivalence.py"
FILES = {".oteleq-owned.json", PROJECT, POLICY, RUNNER, "README.txt", "GENERATED-LICENSE.txt"}
README = """Current-source equivalence tests generated by oteleq.

Run: python3 -I -B test_equivalence.py
For discovery, use python3 -I -B -m unittest discover -s /path/to/this/directory.
An in-repository suite finds its source relative to this directory. An external
suite requires OTELEQ_SOURCE=/absolute/path/to/the/current/application.
OTELEQ_CLI can relocate the same CLI bytes. OTELEQ_PYTHON selects the pinned
adapter environment. OTELEQ_WORKSPACE_PARENT selects an external run parent.

Each discovery creates a fresh private plan and actual per-case unittest suite.
The application, fixtures and policy are not edited. New runs retain their
workspace and observations at the printed path. Changed tool/provider/language
context requires a new reviewed promotion. Unsupported selected functions fail.
Use the same qualified CLI to clean this unchanged owned bundle explicitly.

Evidence means equivalence over these tests and observations, not correctness
for every input or proof about a different shipping artefact.
Boilerplate is MIT licensed; oteleq itself is AGPL-3.0.
"""


def toml_value(value) -> str:
    """Serialise already validated policy values without executing target code."""
    if isinstance(value, dict):
        return "{" + ",".join(json.dumps(key, ensure_ascii=False) + "=" + toml_value(item)
                              for key, item in value.items() if item is not None) + "}"
    if isinstance(value, list):
        return "[" + ",".join(map(toml_value, value)) + "]"
    return json.dumps(value, ensure_ascii=False, allow_nan=False)


def policy_text(configuration: dict) -> str:
    """Keep the resolved policy, including CLI selection overrides, as TOML."""
    text = "\n".join(json.dumps(key, ensure_ascii=False) + "=" + toml_value(value) for key, value in configuration.items()) + "\n"
    if project_policy.validate(tomllib.loads(text)) != configuration:
        raise ValueError("resolved policy cannot be represented as TOML")
    return text


def verify(workflow, bundle: Path) -> tuple[dict, dict]:
    """A project marker hides only exact owned boilerplate and sealed policy."""
    if bundle.is_symlink() or not bundle.is_dir():
        raise ValueError("project suite is not an owned directory")
    entries = list(bundle.iterdir())
    if ({path.name for path in entries} != FILES
            or any(path.is_symlink() or not path.is_file() for path in entries)):
        raise ValueError("project suite contains missing or unowned files")
    marker, data = workflow.read(bundle / workflow.OWNED_MARKER), workflow.read(bundle / PROJECT)
    project_runner.validate_metadata(data)
    if (type(marker) is not dict or set(marker) != {"schema_version", "kind", "id", "project_sha256"}
            or type(marker["schema_version"]) is not int or marker["schema_version"] != 1
            or marker["kind"] != KIND or type(marker["id"]) is not str
            or marker["project_sha256"] != workflow.identity(data)):
        raise ValueError("project suite identity changed")
    files = workflow.manifest(bundle)
    for name in (workflow.OWNED_MARKER, PROJECT):
        del files[name]
    if files != data.get("files_sha256"):
        raise ValueError("project suite content changed")
    here = Path(__file__).parent
    if ((bundle / RUNNER).read_bytes() != (here / "project_runner.py").read_bytes()
            or (bundle / "GENERATED-LICENSE.txt").read_bytes() != (here / "GENERATED-LICENSE.txt").read_bytes()
            or (bundle / "README.txt").read_text() != README):
        raise ValueError("project suite boilerplate is not recognised")
    configuration = workflow.project_policy.validate(tomllib.loads((bundle / POLICY).read_text()))
    if workflow.identity(configuration) != data.get("configuration_sha256"):
        raise ValueError("project suite policy identity changed")
    return marker, data


def destination(workspace: Path, provider: Path, source: Path, selected: Path) -> Path:
    """Promotion creates a new directory without overwriting application content."""
    target = selected.resolve()
    if selected.is_symlink() or target.exists() or source.is_relative_to(target):
        raise ValueError("promotion destination must be new and cannot contain the application")
    for protected in (workspace, provider):
        if target.is_relative_to(protected) or protected.is_relative_to(target):
            raise ValueError("promotion destination overlaps a workspace or provider")
        if source.is_relative_to(protected) or protected.is_relative_to(source):
            raise ValueError("current application overlaps a workspace or provider")
    return target


def promote(args, workflow) -> int:
    """Plan or explicitly write a sealed current-source unittest entrypoint."""
    workspace, data = workflow.load_workspace(args.workspace, generated=True)
    source = args.source.resolve(strict=True)
    if args.source.is_symlink() or not source.is_dir():
        raise ValueError("current application must be a real source directory")
    target = destination(workspace, Path(data["otelc_root"]), source, args.destination)
    workflow.java_project.protect_destination(target, workflow.java_project.original_locations(data))
    here = Path(__file__).parent
    contents = {RUNNER: (here / "project_runner.py").read_bytes(), POLICY: policy_text(data["configuration"]).encode(),
                "README.txt": README.encode(), "GENERATED-LICENSE.txt": (here / "GENERATED-LICENSE.txt").read_bytes()}
    metadata = {"schema_version": 1, "kind": KIND, "source": str(source),
                "source_relative": os.path.relpath(source, target) if target.is_relative_to(source) else None,
                "otelc_root": data["otelc_root"], "cli": os.environ["OTELEQ_EXECUTABLE"],
                "python": sys.executable, "cli_sha256": data["cli_sha256"],
                "generator_sha256": data["generator_sha256"], "configuration_sha256": data["configuration_sha256"],
                "tools": data["tools"], "artefacts": data["artefacts"],
                "promotion_source_sha256": data["source_sha256"],
                "files_sha256": {name: workflow.capture.digest(value) for name, value in contents.items()}}
    contents[PROJECT] = (json.dumps(metadata, sort_keys=True, indent=2) + "\n").encode()
    marker = {"schema_version": 1, "kind": KIND, "id": workflow.identity(metadata)[:32],
              "project_sha256": workflow.identity(metadata)}
    contents[workflow.OWNED_MARKER] = (json.dumps(marker, sort_keys=True, indent=2) + "\n").encode()
    if not args.apply:
        print(json.dumps({"destination": str(target), "source": str(source), "mode": "dry-run",
                          "files": {name: len(value) for name, value in contents.items()},
                          "claim": "equivalence over these tests and observations"}))
        return 0
    target.mkdir(mode=0o700)
    for name, value in contents.items():
        with (target / name).open("xb") as output:
            output.write(value)
    verify(workflow, target)
    print(target)
    return 0
